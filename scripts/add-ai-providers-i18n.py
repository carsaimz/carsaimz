BASE = Path('/home/z/my-project/src/lib/translations')

# Escape single quotes in values for TypeScript string literals
def esc(s):
    return s.replace("\\", "\\\\").replace("'", "\\'")

# Determine the language label for the comment block
LANG_LABEL = {
    'pt-br.ts': 'Provedores de IA (chatbot) — Português (Brasil)',
    'es-es.ts': 'Proveedores de IA (chatbot) — Español',
    'fr-fr.ts': 'Fournisseurs d\'IA (chatbot) — Français',
    'de-de.ts': 'KI-Anbieter (Chatbot) — Deutsch',
    'sw-tz.ts': 'Watoa huduma wa AI (chatbot) — Kiswahili',
    'zh-cn.ts': 'AI 提供商 (聊天机器人) — 中文',
}

for fname, trans in TRANSLATIONS.items():
    p = BASE / fname
    content = p.read_text(encoding='utf-8')
    # Build the block
    lines = [
        '',
        '  // ============================================================================',
        f'  // {LANG_LABEL[fname]}',
        '  // ============================================================================',
        '  aiProviders: {',
    ]
    for k, v in trans.items():
        lines.append(f"    {k}: '{esc(v)}',")
    lines.append('  },')
    lines.append('};')
    block = '\n'.join(lines) + '\n'

    # Find the last closing `},\n};\n` and replace
    marker = '  },\n};\n'
    idx = content.rfind(marker)
    if idx == -1:
        # Try without trailing newline
        marker2 = '  },\n};'
        idx2 = content.rfind(marker2)
        if idx2 == -1:
            print(f'WARNING: marker not found in {fname}')
            continue
        new_content = content[:idx2] + block
    else:
        # Include the part up to and including the last `},` of payment section
        # Replace from `};\n` onwards
        # Find the start of the final `};` (which closes the export const)
        close_idx = content.rfind('\n};')
        if close_idx == -1:
            print(f'WARNING: no closing in {fname}')
            continue
        # The closing is at the end. Replace the closing `};\n` with our new block.
        # Find the last `},` (payment block close) — we want to insert after it.
        # Simpler: take everything before `\n};\n` and append our block.
        new_content = content[:close_idx] + '\n' + block
    p.write_text(new_content, encoding='utf-8')
    print(f'OK: {fname}')

print('Done.')
